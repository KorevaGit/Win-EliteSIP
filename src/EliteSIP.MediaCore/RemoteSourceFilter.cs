namespace EliteSIP.MediaCore;

/// <summary>Что делать с пакетом от источника.</summary>
public enum RemoteSourceVerdict
{
    /// <summary>Наш поток. Обычный случай.</summary>
    Known,

    /// <summary>Чужой источник — выбросить, ничего никому не говоря.</summary>
    Foreign,

    /// <summary>Источник сменился по-настоящему: пакет принять, но буфер выбросить.</summary>
    Adopted,
}

/// <summary>
/// Кто из говорящих на нашем порту — собеседник.
///
/// На открытый UDP-порт прилетает что угодно. Внутри одного адреса источник
/// опознаётся только полем SSRC, и полагаться на то, что он один, нельзя в обе
/// стороны:
///
/// <list type="bullet">
/// <item><b>Принимать всех</b> значит отдать оператору чужой поток вперемешку с
/// настоящим. Номера последовательности у потоков свои, и джиттер-буфер склеит
/// их в кашу, не заметив подмены.</item>
/// <item><b>Отказывать всем, кроме первого</b>, значит однажды замолчать
/// навсегда. Asterisk меняет SSRC, когда меняется мост на его стороне: после
/// перевода, после входа в конференцию, при переходе на музыку ожидания.
/// Проверка в одну строку стоила бы разговора, который оборвался ровно в
/// момент, ради которого его переводили.</item>
/// </list>
///
/// Отсюда середина: чужой источник отбрасывается, но если он приходит подряд и
/// настойчиво, а прежний замолчал, — значит поток действительно сменился, и
/// новый признаётся своим.
///
/// Тип чистый и без замков: решение зависит только от последовательности
/// пришедших SSRC, и проверяется оно тестом, а не прослушиванием разговора.
/// Замок остаётся снаружи, у того, кто зовёт.
/// </summary>
internal sealed class RemoteSourceFilter
{
    /// <summary>
    /// Сколько пакетов подряд нужно новому источнику, чтобы его признали.
    ///
    /// Пять — это сто миллисекунд при обычных двадцати на пакет. Одиночная
    /// подмена столько не живёт, настоящая смена источника проходит незаметно:
    /// четыре потерянных кадра закрывает сокрытие потерь, и на слух это ровно
    /// то же, что одна короткая заминка сети.
    /// </summary>
    public const int AdoptionRun = 5;

    private uint? _candidate;
    private int _candidateRun;

    /// <summary>SSRC, признанный своим. <c>null</c> — первого пакета ещё не было.</summary>
    public uint? Accepted { get; private set; }

    /// <summary>
    /// Забывает собеседника: следующий пакет снова задаст источник.
    ///
    /// Нужно там, где поток пересобирается целиком, — собеседник вернулся с
    /// другого адреса и вполне мог сменить SSRC вместе с ним. Прежний номер про
    /// новый поток не говорит ничего, а оставленный — заставил бы фильтр
    /// отбрасывать законные пакеты первые пять кадров подряд.
    /// </summary>
    public void Forget()
    {
        Accepted = null;
        _candidate = null;
        _candidateRun = 0;
    }

    /// <summary>Разбирает очередной SSRC.</summary>
    public RemoteSourceVerdict Admit(uint ssrc)
    {
        if (Accepted is not uint accepted)
        {
            // Первый пакет разговора и задаёт источник. Спрашивать тут нечего:
            // до него мы не знаем про собеседника вообще ничего.
            Accepted = ssrc;
            return RemoteSourceVerdict.Known;
        }

        if (accepted == ssrc)
        {
            // Прежний источник жив — значит счёт кандидату надо обнулить. Иначе
            // чужой поток, идущий вперемешку с настоящим, однажды накопил бы
            // свои пять пакетов и вытеснил собеседника.
            _candidate = null;
            _candidateRun = 0;
            return RemoteSourceVerdict.Known;
        }

        if (_candidate == ssrc)
        {
            _candidateRun++;
        }
        else
        {
            _candidate = ssrc;
            _candidateRun = 1;
        }

        if (_candidateRun < AdoptionRun)
        {
            return RemoteSourceVerdict.Foreign;
        }

        Accepted = ssrc;
        _candidate = null;
        _candidateRun = 0;
        return RemoteSourceVerdict.Adopted;
    }
}
