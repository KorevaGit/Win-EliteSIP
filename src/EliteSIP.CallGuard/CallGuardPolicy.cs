namespace EliteSIP.CallGuard;

/// <summary>
/// Настройки защиты приёма вызова.
/// </summary>
///
/// <remarks>
/// Сериализуемая потому, что то же самое лежит в файле настроек и на W10
/// приедет из панели EliteSIP. Значения по умолчанию соответствуют разобранным
/// в <c>docs/anti-autoclicker.md</c> мерам; менять их можно, но каждое
/// послабление стоит одного пункта модели угроз.
///
/// Запись, а не класс: политика — значение. Две одинаково настроенные защиты
/// обязаны быть равны, иначе сравнение «настройки изменились» пришлось бы
/// писать по полям, а забытое поле в таком сравнении не видно никак.
/// </remarks>
public sealed record CallGuardPolicy
{
    /// <summary>
    /// Общий выключатель.
    /// </summary>
    ///
    /// <remarks>
    /// Выключить защиту можно, скрыть факт выключения — нет: он пишется в
    /// журнал, а на W10 уедет в панель. Пока это единственный работающий
    /// вариант из трёх, разобранных в документе.
    /// </remarks>
    public bool IsEnabled { get; init; } = true;

    /// <summary>Управляется ли значение сервером.</summary>
    ///
    /// <remarks>
    /// <b>Выводится из режима машины, а не приезжает полем.</b> Машина под
    /// предустановкой показывает управляемые переключатели, но не даёт их
    /// трогать. Полем из файла предустановок этот признак прийти не может и не
    /// должен — это был бы второй источник одного факта; ставит его наложение
    /// управляемых полей, один раз на все сразу. Смысл он получит на W10.
    /// </remarks>
    public bool IsServerManaged { get; init; }

    // MARK: слой 1 — случайность

    public bool IsRandomPositionEnabled { get; init; } = true;

    /// <summary>Правит ли расстояния этого слоя человек.</summary>
    ///
    /// <remarks>
    /// <b>Зачем понадобился отдельный признак.</b> Ползунок в настройках
    /// меняется от одного движения колёсика над ним — и меняется молча: в
    /// отличие от переключателя, у ползунка нет двух состояний, о которых можно
    /// сказать «стало не так, как было». Администратор, прокручивающий страницу
    /// «Входящих», уводил смещение с проверенных 150 точек, узнавал об этом
    /// никогда, а платил за это оператор — окно вставало не там, где защита
    /// рассчитывала.
    ///
    /// Поэтому расстояния по умолчанию не редактируются вовсе, а показываются:
    /// <c>false</c> — «как задумано», и <see cref="Normalized"/> возвращает сюда
    /// заводские значения, чем бы ни было записано в файле. Ручной режим
    /// включается отдельным осознанным действием, и с этого момента числа
    /// принадлежат человеку.
    /// </remarks>
    public bool TunesRandomnessByHand { get; init; }

    /// <summary>Минимальное смещение окна от прошлой позиции, в точках.</summary>
    public double MinimumTravel { get; init; } = 150;

    /// <summary>Отступ от краёв рабочей области, в точках.</summary>
    public double ScreenMargin { get; init; } = 24;

    // Случайной задержки активации здесь больше нет, и это решение, а не
    // потеря. В первой реализации кнопки активировались через 300–1500 мс, но
    // цену платил оператор на каждом вызове, а кликер эту задержку просто
    // пережидает. Подозрительно ровное время реакции ловится статистикой
    // панели, для чего в отчёте и лежит `ReactionMilliseconds`. Ключи из
    // старого файла настроек молча игнорируются: таких свойств здесь нет, а
    // разбор чужих ключей не падает и не подхватывает их.

    /// <summary>
    /// Сколько кнопок-целей показывать. Единица означает обычную кнопку
    /// «Ответить» без выбора.
    /// </summary>
    ///
    /// <remarks>
    /// По умолчанию именно единица. Основная мера — случайная позиция окна: она
    /// ломает кликер по координатам и при этом ничего не стоит оператору.
    /// Цифровое подтверждение стоит внимания на каждом вызове, поэтому
    /// включается отдельно и осознанно — против кликера по шаблону изображения,
    /// когда такой появится.
    /// </remarks>
    public int TargetCount { get; init; } = 1;

    // MARK: слой 2 — признаки живого человека

    /// <summary>Требовать движения курсора перед приёмом вызова.</summary>
    public bool RequiresCursorMovement { get; init; } = true;

    /// <summary>
    /// Правит ли расстояния этого слоя человек. Довод тот же, что у
    /// <see cref="TunesRandomnessByHand"/>, и цена ошибки здесь выше: заниженный
    /// путь курсора не ломает ничего на глаз, а защиту снимает.
    /// </summary>
    public bool TunesLivenessByHand { get; init; }

    /// <summary>Сколько точек курсор должен пройти. Телепорт в точку даёт ноль.</summary>
    public double RequiredCursorTravel { get; init; } = 40;

    /// <summary>Сколько отдельных перемещений должно случиться. Одно — это прыжок.</summary>
    public int RequiredCursorSamples { get; init; } = 3;

    /// <summary>Отклонять нажатия с признаком программного происхождения.</summary>
    ///
    /// <remarks>
    /// В Windows признак честнее, чем был на macOS: низкоуровневый хук мыши
    /// отдаёт <c>LLMHF_INJECTED</c>, то есть клик от <c>SendInput</c> виден
    /// явно. Подделать его всё же можно — драйвером, — поэтому по умолчанию это
    /// не барьер, а сигнал в телеметрию: у честного оператора он не встречается
    /// никогда. Включённое отклонение ловит простые кликеры, но может задеть
    /// оператора со средствами доступности.
    /// </remarks>
    public bool RejectsSyntheticEvents { get; init; }

    /// <summary>Приведение к работоспособному виду.</summary>
    ///
    /// <remarks>
    /// Нужно, потому что настройки редактируются снаружи: ноль целей или
    /// отрицательный путь курсора выключили бы защиту молча, а молчаливо
    /// выключенная защита хуже честно выключенной.
    /// </remarks>
    public CallGuardPolicy Normalized()
    {
        var factory = new CallGuardPolicy();

        // Автоматический слой возвращает заводские расстояния, а не подрезает
        // записанные. Разница видна ровно в том случае, ради которого признак и
        // заведён: файл настроек, в котором смещение однажды сдвинули, на
        // «Авто» больше не действует — иначе «Авто» означало бы «то, что
        // осталось от прошлой правки», а не «как задумано».
        return this with
        {
            TargetCount = Math.Min(Math.Max(1, TargetCount), CallGuardChallenge.MaximumTargets),

            MinimumTravel = TunesRandomnessByHand ? Math.Max(0, MinimumTravel) : factory.MinimumTravel,
            ScreenMargin = TunesRandomnessByHand ? Math.Max(0, ScreenMargin) : factory.ScreenMargin,

            RequiredCursorTravel = TunesLivenessByHand
                ? Math.Max(0, RequiredCursorTravel)
                : factory.RequiredCursorTravel,
            RequiredCursorSamples = TunesLivenessByHand
                ? Math.Max(0, RequiredCursorSamples)
                : factory.RequiredCursorSamples,
        };
    }

    /// <summary>
    /// Защита, выключенная целиком. Окно ведёт себя как обычное: одна кнопка в
    /// середине экрана, курсор ничего не должен.
    /// </summary>
    ///
    /// <remarks>
    /// <see cref="TunesRandomnessByHand"/> и <see cref="TunesLivenessByHand"/>
    /// здесь <b>включены</b>, и это не копипаста: на «Авто»
    /// <see cref="Normalized"/> вернул бы заводские сорок точек пути курсора —
    /// то есть выключенная защита требовала бы движения мыши.
    /// </remarks>
    public static CallGuardPolicy Disabled { get; } = new()
    {
        IsEnabled = false,
        IsRandomPositionEnabled = false,
        TunesRandomnessByHand = true,
        MinimumTravel = 0,
        ScreenMargin = 0,
        TargetCount = 1,
        RequiresCursorMovement = false,
        TunesLivenessByHand = true,
        RequiredCursorTravel = 0,
        RequiredCursorSamples = 0,
        RejectsSyntheticEvents = false,
    };
}
