using System.Security.Cryptography;
using System.Text;

namespace EliteSIP.AdminAccess;

/// <summary>
/// PBKDF2-HMAC-SHA256 — единственный способ, которым пароль превращается в
/// байты.
///
/// Не голый SHA-256: пароль администратора человек придумывает сам, и по одному
/// быстрому хешу словарь из миллиона вариантов перебирается за секунды. PBKDF2
/// умножает цену перебора на число итераций, и это единственное, что в принципе
/// можно противопоставить короткому паролю.
///
/// В оригинале здесь был CommonCrypto — CryptoKit не годился, потому что его
/// HKDF появился только в macOS 11, а сборка жила с Catalina. В .NET такого
/// выбора нет: <see cref="Rfc2898DeriveBytes"/> — та же функция, и её
/// статическая перегрузка не требует ни времени жизни объекта, ни ручной работы
/// с указателями. Весь файл поэтому втрое короче оригинала, а решения в нём —
/// те же самые.
/// </summary>
internal static class KeyDerivation
{
    /// <summary>
    /// Итераций по умолчанию.
    ///
    /// Число подобрано под самую слабую целевую машину, а не под эту: платятся
    /// эти доли секунды один раз за нажатие «Войти». Значение хранится в самих
    /// учётных данных, поэтому его можно поднять, не ломая уже настроенные
    /// рабочие места.
    /// </summary>
    internal const int DefaultIterations = 150_000;

    /// <summary>
    /// Потолок числа итераций, принимаемого из файла.
    ///
    /// Число приезжает снаружи — из настроек, которые правит человек.
    /// <c>iterations: 2000000000</c> — это не стойкость, а зависший процесс:
    /// PBKDF2 честно отработает столько, сколько попросили, и произойдёт это на
    /// нажатии «Войти», то есть будет выглядеть как зависшее приложение, а не
    /// как испорченный файл.
    ///
    /// Миллион — предел терпения, а не предел работы.
    /// </summary>
    internal const int MaximumIterations = 1_000_000;

    /// <summary>
    /// Нижней границы намеренно нет.
    ///
    /// Она выглядела бы уместной — «тысяча итераций это слабо», — но не даёт
    /// ничего. Своё мы пишем только с <see cref="DefaultIterations"/>; маленькое
    /// число может появиться лишь от правки файла руками, а тот, кто правит
    /// файл, с тем же успехом перепишет учётные данные целиком, своим паролем и
    /// своей солью. Пол защищал бы от противника, которому он не мешает, и ломал
    /// бы проверки, которым дорогой перебор не нужен.
    ///
    /// Что происходит с подделанным сверху: проверка не сходится, и человек
    /// видит «неверный пароль». Это и есть цель — превратить зависание в отказ.
    /// </summary>
    internal static int BoundedIterations(int value) => Math.Min(value, MaximumIterations);

    /// <summary>
    /// Байты, выведенные из строки и соли.
    ///
    /// Пустая соль отвергается: без неё одинаковые пароли на разных машинах
    /// дают одинаковый хеш, и радужная таблица снова становится осмысленной.
    /// </summary>
    internal static byte[] Derive(string secret, byte[] salt, int iterations, int byteCount = 32)
    {
        ArgumentNullException.ThrowIfNull(secret);
        ArgumentNullException.ThrowIfNull(salt);

        if (salt.Length == 0 || iterations <= 0 || byteCount <= 0)
        {
            throw new AdminAccessException(AdminAccessFailure.MalformedCredential);
        }

        try
        {
            return Rfc2898DeriveBytes.Pbkdf2(
                Encoding.UTF8.GetBytes(secret),
                salt,
                iterations,
                HashAlgorithmName.SHA256,
                byteCount);
        }
        catch (CryptographicException error)
        {
            // Тот же случай, что и ненулевой статус CommonCrypto в оригинале:
            // отказ криптопровайдера не превращается в молчаливый нулевой ключ.
            throw new AdminAccessException(AdminAccessFailure.DerivationFailed, error);
        }
    }

    /// <summary>
    /// Случайная соль.
    ///
    /// Запасного генератора, в отличие от оригинала, нет:
    /// <see cref="RandomNumberGenerator"/> при отказе источника энтропии бросает,
    /// а не возвращает мусор, и подменять его своим было бы ровно тем, чего в
    /// оригинале избегали, — предсказуемой солью.
    /// </summary>
    internal static byte[] RandomSalt(int byteCount = 16) => RandomNumberGenerator.GetBytes(byteCount);

    /// <summary>
    /// Сравнение за постоянное время.
    ///
    /// Обычное сравнение выходит на первом несовпавшем байте, и по времени
    /// ответа хеш подбирается побайтово. Здесь это скорее гигиена, чем защита от
    /// реальной атаки — мерить время локального диалога некому, — но правило
    /// «секреты сравниваются так» дешевле соблюдать всегда, чем вспоминать, где
    /// оно действительно нужно.
    /// </summary>
    internal static bool ConstantTimeEquals(byte[] left, byte[] right)
        => CryptographicOperations.FixedTimeEquals(left, right);
}
