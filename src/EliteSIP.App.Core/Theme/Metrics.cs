namespace EliteSIP.App.Theme;

/// <summary>
/// Единственное место, где заданы размеры и отступы. Оригинал — <c>Theme.swift</c>
/// macOS-версии; числа те же, потому что макет в Figma тот же.
/// </summary>
///
/// <remarks>
/// Точка WPF и точка macOS — это одно и то же: обе независимы от плотности
/// экрана и на масштабе 100% равны пикселю. Поэтому числа переносятся как есть,
/// а не пересчитываются, и макет остаётся одним на две платформы.
///
/// Чего здесь сознательно нет — высоты полосы заголовка. У панели она своя,
/// нарисованная (<c>PanelChrome</c>), и её высота объявлена рядом с вёрсткой,
/// а не тут: на macOS полосу рисовала система и число приходилось спрашивать
/// у неё, здесь спрашивать некого.
/// </remarks>
internal static class Metrics
{
    /// <summary>
    /// Панель узкая и фиксированной ширины — это софтфон, а не окно почты.
    /// </summary>
    ///
    /// <remarks>
    /// 270 — компромисс редизайна: дайлпада, ради которого держались 280,
    /// больше нет, а подписи макросов в три колонки перестают ужиматься до
    /// нечитаемого. Окно висит поверх CRM весь рабочий день, и каждая лишняя
    /// точка ширины отъедает место у того, с чем оператор реально работает.
    ///
    /// В плане переноса стоит «панель 280×500» — это цифры аудита, снятые до
    /// редизайна. Настоящий размер macOS-версии здесь.
    /// </remarks>
    public const double PanelWidth = 270;

    /// <summary>Высота, с которой окно панели создаётся до первого прохода раскладки.</summary>
    ///
    /// <remarks>
    /// Настоящую высоту панель считает сама из числа макросов. Здесь нужно
    /// какое-то значение до первого измерения — иначе окно мигнёт размером.
    /// </remarks>
    public const double PanelInitialHeight = 250;

    /// <summary>Строка состояния: капсула профиля, слот беды, шестерёнка.</summary>
    ///
    /// <remarks>
    /// Стоит под полосой заголовка, а не в ней. Раньше делила линию со
    /// светофором ради экономии 28 точек, и это стоило двух вещей: у окна не
    /// было имени, а номер стоял так близко к кнопкам окна, что читался как
    /// ещё одна из них.
    /// </remarks>
    public const double StatusBarHeight = 22;

    /// <summary>Сторона подсветки под курсором у кнопок строки состояния.</summary>
    public const double StatusIconHitSize = 22;

    /// <summary>Высота капсулы профиля: капсула и есть строка состояния.</summary>
    public const double ProfilePickerHeight = 22;

    /// <summary>Сколько места в строке состояния капсула отобрать не может.</summary>
    ///
    /// <remarks>
    /// Ширина капсулы плавает от длины пометки профиля, а слот беды обязан
    /// оставаться читаемым: «Нет сети» важнее пометки, которую оператор и так
    /// знает, раз сидит за этой машиной.
    /// </remarks>
    public const double TroubleSlotMinWidth = 72;

    /// <summary>Точка состояния в капсуле.</summary>
    ///
    /// <remarks>
    /// 8, а не прежние 6: точка осталась единственным, чем показано обычное
    /// состояние. Подпись «На линии» рядом с зелёным кружком занимала место и
    /// не сообщала ничего сверх него.
    /// </remarks>
    public const double StatusDotDiameter = 8;

    /// <summary>Высота шапки — одна на все состояния панели.</summary>
    ///
    /// <remarks>
    /// Поле набора в покое и карточка собеседника в разговоре занимают ровно
    /// столько же: иначе при ответе на вызов шапка вырастала бы и сдвигала
    /// вниз всё, что под ней. При двух линиях слот делится на два поля по 22.
    /// </remarks>
    public const double HeaderHeight = 52;

    /// <summary>Высота поля одной линии, когда их в шапке две.</summary>
    public const double LineFieldHeight = 22;

    /// <summary>Точка состояния линии. Мельче, чем у профиля: линий две.</summary>
    public const double LineDotDiameter = 6;

    /// <summary>Кегль набираемого номера.</summary>
    public const double DialedNumberSize = 18;

    /// <summary>Неподвижная нижняя зона: кнопка звонка и история.</summary>
    public const double ActionHeight = 46;

    /// <summary>
    /// Ширина «Истории». Задана явно, чтобы кнопка звонка занимала весь
    /// остаток и не меняла ширину от длины подписи.
    /// </summary>
    public const double HistoryWidth = 64;

    /// <summary>Ряд управления: удержание, микрофон, перевод, конференция.</summary>
    ///
    /// <remarks>
    /// Ниже клавиш макросов и с подписью в строку, а не столбиком, — так ряд
    /// читается как другой класс элементов, а не как первый ряд сетки.
    /// </remarks>
    public const double ControlHeight = 32;

    /// <summary>Поле ввода номера перевода.</summary>
    public const double TransferFieldHeight = 34;

    /// <summary>Кнопки под полем перевода.</summary>
    public const double TransferButtonHeight = 30;

    /// <summary>
    /// Ниже этого клавиша макроса не сжимается. Верхнего предела нет: сетка
    /// забирает всю свободную вертикаль, иначе между ней и кнопкой завершения
    /// оставался бы провал, который нечем занять.
    /// </summary>
    public const double MacroMinHeight = 58;

    /// <summary>
    /// Три в ряд: подпись макроса задаёт администратор, предсказать её ширину
    /// нельзя, но три коротких кнопки в 250 точек влезают всегда.
    /// </summary>
    public const int MacroColumns = 3;

    // Шкала отступов: 2 / 4 / 6 / 8 / 12. Пять ступеней на всё, и всё, что
    // отступает, отступает одной из них.
    //
    // До редизайна в вёрстке жили одиннадцать значений — 1, 2, 3, 4, 5, 6, 8,
    // 10, 12, 14, — и половина отличалась друг от друга на точку, то есть не
    // отличалась вовсе: разницу между 3 и 4 глаз не видит, а необходимость
    // каждый раз выбирать между ними — вполне.
    //
    // Вертикальные промежутки между ярусами панели сюда не входят: они
    // неравные по смыслу и живут поимённо в `Gap`.

    /// <summary>2 — волосок.</summary>
    public const double HairSpacing = 2;

    /// <summary>4 — вплотную.</summary>
    public const double TightSpacing = 4;

    /// <summary>6 — между элементами одного ряда.</summary>
    public const double ElementSpacing = 6;

    /// <summary>8 — между разделами.</summary>
    public const double SectionSpacing = 8;

    /// <summary>12 — поля содержимого.</summary>
    public const double ContentPadding = 12;

    /// <summary>Непрозрачность выключенного элемента.</summary>
    ///
    /// <remarks>
    /// 0.57, а не прежние 0.35: три почти невидимые кнопки читались как
    /// сломанные, а не как «пока нечем пользоваться». Число одно на обе темы —
    /// разное означало бы, что выключенность в одной из них читается иначе, а
    /// это одно и то же состояние.
    /// </remarks>
    public const double DisabledOpacity = 0.57;
}

/// <summary>
/// Вертикальные промежутки между ярусами. Заданы поимённо, а не общим шагом:
/// расстояния здесь неравные по смыслу.
/// </summary>
internal static class Gap
{
    /// <summary>Полоса заголовка → строка состояния.</summary>
    ///
    /// <remarks>
    /// Меньше остальных: капсула профиля относится к заголовку — тот же вопрос
    /// «что это за окно», только с ответом «и под каким номером».
    /// </remarks>
    public const double TitleToStatus = 4;

    /// <summary>Строка состояния → шапка.</summary>
    public const double StatusToHeader = 5;

    /// <summary>Шапка → ряд управления. Соседи одного действия.</summary>
    public const double HeaderToControls = 5;

    /// <summary>Ряд управления → макросы. Разные классы, разделяет воздух.</summary>
    public const double ControlsToMacros = 15;

    /// <summary>Макросы → кнопка завершения.</summary>
    public const double MacrosToAction = 15;

    /// <summary>Шапка окна входящего → карточка вызова.</summary>
    public const double IncomingHeaderToCaller = 8;

    /// <summary>Карточка вызова → кнопки. Дальше: это уже действие.</summary>
    public const double IncomingCallerToActions = 14;
}

/// <summary>
/// Размеры значков: три, и только три.
/// </summary>
///
/// <remarks>
/// Было четыре — 10, 11, 12, 13, — и соседние отличались на точку, то есть не
/// отличались. Три ступени различимы: мелкая при подписи, средняя в кнопках
/// строки состояния, крупная в неподвижном низу, где значок работает вместо
/// подписи.
/// </remarks>
internal static class IconSizes
{
    public const double Small = 10;
    public const double Medium = 12;
    public const double Large = 14;

    /// <summary>Значок в боковом списке разделов.</summary>
    ///
    /// <remarks>
    /// На точку меньше системных 16: наши значки нарисованы на сетке 20×20
    /// обводкой 1.5 и не масштабируются как системные — на 16 их обводка
    /// читается грубее соседних системных элементов.
    /// </remarks>
    public const double Sidebar = 15;
}

/// <summary>Радиусов два, и третьего числа здесь не будет.</summary>
internal static class Radius
{
    /// <summary>Поверхность: карточка, плашка, окно.</summary>
    public const double Surface = 12;

    /// <summary>Элемент управления: кнопка, поле, подсветка значка.</summary>
    ///
    /// <remarks>
    /// Сюда же сведена необъявленная «шестёрка», жившая в трёх местах:
    /// разница в две точки глазом не читается, а третье число в наборе —
    /// вполне.
    /// </remarks>
    public const double Control = 8;

    /// <summary>Радиус капсулы — половина её высоты, а не третье число.</summary>
    public static double Capsule(double height) => height / 2;
}
