namespace EliteSIP.CallHistory;

/// <summary>
/// Номер, с которого на эту машину приходили вызовы, и когда это было в
/// последний раз.
///
/// Заведён под подсказки словаря очередей: администратор не может узнать номера
/// очередей ниоткуда, кроме как спросив у заказчика, — боевой Asterisk у нас на
/// чтение, — а ошибка в цифре не проявляется никак: вызов просто остаётся без
/// названия, молча. Подсказка предлагает то, что действительно приходило.
///
/// Не запись звонка: ни собеседника, ни исхода, ни длительности здесь нет.
/// Словарю нужен номер, а истории на этом экране не место.
/// </summary>
/// <param name="Number">Номер, как он приходил.</param>
/// <param name="LastCall">Когда приходил в последний раз.</param>
/// <param name="Count">
/// Сколько раз приходил. Отличает настоящую очередь от единственного звонка с
/// внутреннего добавочного, который в словарь не нужен.
/// </param>
public readonly record struct NumberSighting(string Number, DateTimeOffset LastCall, int Count)
{
    /// <summary>
    /// Сколько в номере цифр. Всё остальное — плюсы, скобки и дефисы — на длину
    /// не влияет: один и тот же номер приходит записанным по-разному.
    /// </summary>
    public int DigitCount
    {
        get
        {
            int digits = 0;
            foreach (char character in Number)
            {
                if (char.IsDigit(character))
                {
                    digits++;
                }
            }

            return digits;
        }
    }
}
