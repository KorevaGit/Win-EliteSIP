namespace EliteSIP.CallHistory;

/// <summary>Куда шёл звонок.</summary>
public enum CallDirection
{
    Incoming = 0,
    Outgoing = 1,
}

/// <summary>
/// Основная линия или консультационная.
///
/// То, что в плане названо «линия». Хранится смыслом, а не номером линии: сам
/// номер — это локальный Call-ID, он уже лежит в <c>CallId</c>, а человеку,
/// который смотрит историю, важно другое — этот звонок он набрал сам или это
/// была консультация посреди чужого разговора.
/// </summary>
public enum CallRole
{
    Primary = 0,
    Consultation = 1,
}

/// <summary>
/// Чем кончился звонок — одним словом.
///
/// <b>Кодом, а не разбором строки.</b> Причина уже хранится в <c>EndReason</c>
/// той же формулировкой, которую видел оператор на панели, и вывести из неё
/// короткое слово можно было бы сравнением с образцами. Так делать нельзя:
/// стоит поменять формулировку на панели — и история молча начнёт писать «отказ»
/// вместо «занято», причём ни один тест этого не заметит, потому что обе строки
/// правильные, просто разные. Код ставится в момент, когда ответ сервера ещё
/// разобран на части, и после этого не зависит ни от чьих слов.
///
/// Значения начинаются с единицы: колонка появилась миграцией и у старых записей
/// пуста, а чтение целого отдаёт ноль и на пустоту тоже. Ноль как «код не
/// записан» позволяет не заводить отдельное чтение ради одной колонки.
/// </summary>
public enum CallOutcome
{
    /// <summary>Разговор состоялся. Слова у него нет — вместо него длительность.</summary>
    Completed = 1,

    /// <summary>Входящий, на который не ответили.</summary>
    Missed = 2,

    /// <summary>486, 600.</summary>
    Busy = 3,

    /// <summary>408, 480, 487 — никто не снял трубку, или мы не дождались.</summary>
    NoAnswer = 4,

    /// <summary>404.</summary>
    UnknownNumber = 5,

    /// <summary>403, 603.</summary>
    Declined = 6,

    /// <summary>Всё остальное. Код ответа остаётся в <c>EndReason</c> и в журнале.</summary>
    Failed = 7,
}

/// <summary>Словарь исходов: слово для строки и перевод кода ответа SIP.</summary>
public static class CallOutcomes
{
    /// <summary>
    /// Слово в колонке длительности. Шесть слов на все неудачи, и это потолок:
    /// седьмое означало бы, что оператору предлагают различать то, на что он всё
    /// равно ответит одинаково.
    ///
    /// <c>null</c> у состоявшегося разговора — там стоит длительность.
    /// </summary>
    public static string? Title(this CallOutcome outcome) => outcome switch
    {
        CallOutcome.Completed => null,
        CallOutcome.Missed => Resources.PackageStrings.Get("OutcomeMissed"),
        CallOutcome.Busy => Resources.PackageStrings.Get("OutcomeBusy"),
        CallOutcome.NoAnswer => Resources.PackageStrings.Get("OutcomeNoAnswer"),
        CallOutcome.UnknownNumber => Resources.PackageStrings.Get("OutcomeUnknownNumber"),
        CallOutcome.Declined => Resources.PackageStrings.Get("OutcomeDeclined"),
        _ => Resources.PackageStrings.Get("OutcomeFailed"),
    };

    /// <summary>
    /// Перевод кода ответа SIP в слово.
    ///
    /// Живёт здесь, а не в приложении, потому что рядом с самим словарём:
    /// добавить исход и забыть про отображение — то же самое, что добавить его
    /// без смысла.
    /// </summary>
    public static CallOutcome ForFailure(int status) => status switch
    {
        486 or 600 => CallOutcome.Busy,
        404 => CallOutcome.UnknownNumber,
        403 or 603 => CallOutcome.Declined,
        // 487 — это наш же CANCEL: мы положили трубку раньше, чем взяли ту. Для
        // оператора это неотличимо от «не ответил», и различать их отдельным
        // словом означало бы объяснять ему устройство SIP.
        408 or 480 or 487 => CallOutcome.NoAnswer,
        _ => CallOutcome.Failed,
    };
}

/// <summary>
/// Одна строка истории звонков.
///
/// Запись заводится в момент, когда звонок начался, и дописывается по ходу:
/// ответ, перевод, конференция, завершение. Так она переживает принудительное
/// завершение приложения — а оно посреди разговора вполне реально, и «пишем в
/// конце» означало бы, что теряются ровно те звонки, после которых софтфон упал.
///
/// Идентификатор свой, а не <c>rowid</c> из базы: он нужен вызывающему сразу,
/// чтобы потом дописать в ту же строку ответ и завершение, а ждать ответа от
/// диска в момент начала звонка нельзя.
///
/// Время — <see cref="DateTimeOffset"/>, а не <see cref="DateTime"/>: в базе оно
/// лежит секундами от эпохи, как в оригинале, а <see cref="DateTime"/> умеет
/// приехать без разметки пояса и превратиться в местное молча. Здесь вопрос
/// «какой это был момент» отвечается однозначно, а «какие это были сутки» —
/// отдельно и явно, календарём вызывающего.
/// </summary>
public sealed record CallRecord
{
    public Guid Id { get; init; } = Guid.NewGuid();

    /// <summary>
    /// Локальный SIP Call-ID. По нему звонок ищут в журнале приложения, когда
    /// история и журнал расходятся в показаниях.
    /// </summary>
    public required string CallId { get; init; }

    /// <summary>
    /// Идентификатор звонка со стороны сервера.
    ///
    /// Пустует до M9. Заведён сейчас, а не тогда, ровно ради того, чтобы в M9
    /// локальная запись склеилась с CDR из EliteDash, а не задвоилась: без
    /// общего ключа сопоставлять пришлось бы по времени и номеру, а это
    /// угадывание, которое ошибается на очереди и на переводах.
    /// </summary>
    public string? ServerCallId { get; set; }

    public required CallDirection Direction { get; init; }

    public CallRole Role { get; init; } = CallRole.Primary;

    /// <summary>
    /// Номер собеседника, как он пришёл. Не нормализуется и не маскируется:
    /// решение оригинала от 30 июля 2026 — номера лидов пишутся как есть.
    /// </summary>
    public required string Number { get; init; }

    /// <summary>
    /// Техническое имя extension из FreePBX, если сервер его прислал.
    ///
    /// Отдельно от номера: на входящем из очереди это разные вещи, и по логину
    /// звонок опознают на стороне АТС.
    /// </summary>
    public string? SipLogin { get; init; }

    /// <summary>
    /// Понятное имя. Может быть переопределено синхронизацией с EliteDash.
    ///
    /// Именно <b>отдельное поле</b>, а не замена номеру и логину. Записать
    /// псевдоним поверх исходного нельзя: пересчитать его заново потом будет не
    /// из чего, а список имён у EliteDash со временем меняется — и вчерашняя
    /// история осталась бы с позавчерашними именами без возможности исправить.
    /// </summary>
    public string? DisplayName { get; set; }

    /// <summary>Профиль, с которого шёл звонок.</summary>
    public Guid? ProfileId { get; init; }

    /// <summary>
    /// Метка профиля на момент звонка.
    ///
    /// Копией, а не ссылкой на профиль: метку правит сам менеджер, профиль может
    /// быть удалён, а история обязана остаться читаемой. Иначе строка годичной
    /// давности показывала бы сегодняшнее название или пустоту.
    /// </summary>
    public string? ProfileLabel { get; init; }

    public DateTimeOffset StartedAt { get; init; } = DateTimeOffset.Now;

    /// <summary>Когда звонок ответили. <c>null</c> — не ответили вовсе.</summary>
    public DateTimeOffset? AnsweredAt { get; set; }

    /// <summary>
    /// Когда звонок закончился. <c>null</c> — ещё идёт либо приложение
    /// завершилось посреди разговора и запись не успела закрыться.
    /// </summary>
    public DateTimeOffset? EndedAt { get; set; }

    /// <summary>Причина завершения — той же строкой, что видел оператор на панели.</summary>
    public string? EndReason { get; set; }

    /// <summary>
    /// Код исхода, записанный в момент завершения.
    ///
    /// <c>null</c> у записей, заведённых до появления колонки, и у тех, чей исход
    /// выводится однозначно и без сервера, — см. <see cref="Outcome"/>.
    /// </summary>
    public CallOutcome? OutcomeCode { get; set; }

    public bool WasTransferred { get; set; }

    public bool WasConference { get; set; }

    /// <summary>
    /// Пришёл ли этот вызов раздачей лида.
    ///
    /// Хранится, а не выводится заново при показе, и это принципиально. Раздачу
    /// отличает от звонка коллеги единственный признак — заголовок
    /// <c>X-Autoanswer</c> во входящем INVITE, — а он живёт ровно столько,
    /// сколько сам вызов. Номер и имя, которые остаются в записи, у раздачи и у
    /// коллеги неотличимы: у обоих внутренний добавочный и подпись.
    ///
    /// <c>false</c> у записей, заведённых до появления колонки: старую раздачу
    /// история покажет номером. Пересчитать её задним числом не из чего.
    /// </summary>
    public bool WasDistribution { get; init; }

    /// <summary>Разговор состоялся.</summary>
    public bool IsAnswered => AnsweredAt is not null;

    /// <summary>
    /// Пропущенный — входящий, на который не ответили.
    ///
    /// Исходящий без ответа пропущенным не считается: его никто не пропускал,
    /// там просто не взяли трубку, и в фильтре «пропущенные» ему делать нечего.
    /// </summary>
    public bool IsMissed => Direction == CallDirection.Incoming && AnsweredAt is null;

    /// <summary>
    /// Длительность разговора — от ответа до конца, а не от начала.
    ///
    /// <c>null</c>, пока разговор не закончился или не начинался. Гудки в
    /// длительность не входят: «две минуты» в истории должны значить две минуты
    /// разговора, иначе сравнивать записи между собой бессмысленно.
    /// </summary>
    public TimeSpan? Duration
        => AnsweredAt is { } answered && EndedAt is { } ended
            ? (ended > answered ? ended - answered : TimeSpan.Zero)
            : null;

    /// <summary>Что показать в строке вместо номера, когда есть что.</summary>
    public string Title
        => !string.IsNullOrEmpty(DisplayName)
            ? DisplayName
            : (Number.Length == 0 ? Resources.PackageStrings.Get("UnknownNumber") : Number);

    /// <summary>
    /// Исход, как его показывает история.
    ///
    /// Записанный код — не единственный источник, и это сделано нарочно. Две
    /// вещи выводятся однозначно и без сервера: состоявшийся разговор виден по
    /// времени ответа, а пропущенный — по направлению вместе с его отсутствием.
    /// Хранить их кодом значило бы завести второе место, где может лежать другая
    /// правда, — а фильтр «Пропущенные» всё равно отбирает по <c>answered_at</c>,
    /// и разойтись эти два ответа не имеют права.
    ///
    /// Порядок проверок поэтому такой: ответили — разговор; входящий без
    /// ответа — пропущенный; дальше уже то, что сказал сервер; а если он не
    /// сказал ничего (запись до миграции, обрыв без ответа) — «не ответил».
    /// </summary>
    public CallOutcome Outcome
    {
        get
        {
            if (IsAnswered)
            {
                return CallOutcome.Completed;
            }

            if (Direction == CallDirection.Incoming)
            {
                return CallOutcome.Missed;
            }

            return OutcomeCode ?? CallOutcome.NoAnswer;
        }
    }
}
