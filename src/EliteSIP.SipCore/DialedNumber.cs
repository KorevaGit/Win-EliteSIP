using System.Text;

namespace EliteSIP.SipCore;

/// <summary>
/// Приведение набранного номера к тому, что можно положить в Request-URI.
///
/// Номер редко набирают руками — его копируют из CRM, а там он записан для
/// человека: <c>+7 (918) 000-11-22</c>. Скобки и пробелы в user-part ломают
/// разбор SIP, поэтому раньше такой номер либо уходил на сервер как есть и не
/// дозванивался, либо возвращал оператору отказ «недопустимые символы» — то
/// есть наказывал его за формат чужого источника.
///
/// Живёт в SipCore, а не во вьюхе, по двум причинам. Во-первых, это правило про
/// протокол, а не про оформление: что допустимо в user-part, решает RFC 3261, а
/// не панель. Во-вторых, здесь его видно тестам.
/// </summary>
public static class DialedNumber
{
    /// <summary>
    /// Символы, которые остаются.
    ///
    /// Цифры — очевидно. Звёздочка и решётка — потому что это обычные добавочные
    /// и коды сервисов АТС (<c>*97</c>), а не украшение. Плюс — потому что
    /// международный формат отличается от местного только им, и потерять его
    /// значит позвонить не туда.
    ///
    /// Всё остальное вырезается молча: скобки, дефисы, точки, обычные и
    /// неразрывные пробелы, невидимые отметки направления письма — их щедро
    /// подкладывают веб-страницы, из которых номер и копируют.
    /// </summary>
    private const string Kept = "0123456789*#";

    /// <summary>
    /// Приводит номер к виду, в котором он уйдёт на сервер.
    ///
    /// Правило одно: показывать в поле ровно то, что уйдёт в INVITE. Иначе
    /// оператор видит один номер, а звонок идёт на другой, и разбираться с этим
    /// приходится по журналу. По той же причине приведение российского номера к
    /// виду маршрута стоит здесь, а не в момент звонка: подмена восьмёрки на
    /// семёрку украдкой при отправке — это ровно тот случай, когда в поле одно,
    /// а позвонило другое.
    /// </summary>
    public static string Normalized(string raw)
    {
        var digits = new StringBuilder(raw.Length);

        // Плюс имеет смысл только в начале: `8+123` — это не международный
        // номер, а опечатка, и сохранять в ней плюс значит сохранять опечатку.
        bool plus = false;

        foreach (char character in raw)
        {
            if (character == '+')
            {
                if (digits.Length == 0 && !plus)
                {
                    plus = true;
                }
                continue;
            }
            if (Kept.Contains(character, StringComparison.Ordinal))
            {
                digits.Append(character);
            }
        }

        string number = digits.ToString();
        return Russian(plus, number) ?? (plus ? "+" + number : number);
    }

    /// <summary>
    /// Российский номер в том виде, в каком его принимает АТС: <c>7</c> и
    /// десять цифр, без плюса.
    ///
    /// Номер приезжает к оператору из трёх источников сразу, и каждый пишет его
    /// по-своему: CRM отдаёт <c>+7 918 000-11-22</c>, клиент диктует «восемь
    /// девятьсот восемнадцать», сам оператор набирает как привык. Исходящий
    /// маршрут АТС понимает ровно одну запись — и все прочие возвращались
    /// отказом, за который оператор расплачивался повторным набором.
    ///
    /// Правило намеренно узкое: срабатывает только на одиннадцати цифрах,
    /// начинающихся с 7 или 8, и только когда в номере нет звёздочки и решётки.
    /// Всё остальное проходит мимо нетронутым — трёхзначный добавочный,
    /// сервисный код <c>*97</c>, международный <c>+1</c>. Иначе клиент принимал
    /// бы решения за чужой диалплан, который мы не видим.
    /// </summary>
    /// <returns>Канонический вид или <see langword="null"/>, если номер не российский.</returns>
    private static string? Russian(bool plus, string digits)
    {
        if (digits.Contains('*', StringComparison.Ordinal) || digits.Contains('#', StringComparison.Ordinal))
        {
            return null;
        }
        if (digits.Length != 11)
        {
            return null;
        }

        return digits[0] switch
        {
            // `+7…` и `7…` — один и тот же номер: плюс здесь только признак
            // формата, а маршрут его не ждёт.
            '7' => digits,

            // Междугородная восьмёрка — местная запись того же кода страны.
            // Плюс перед ней означает опечатку (`+8918…`), и подменять код
            // страны в таком номере нельзя: `+8` — это не Россия.
            '8' => plus ? null : "7" + digits[1..],

            _ => null,
        };
    }

    /// <summary>
    /// Годится ли номер для звонка.
    ///
    /// Пустой не годится, и одного плюса тоже мало: он не номер, а признак
    /// формата.
    /// </summary>
    public static bool IsDialable(string raw) => Normalized(raw).TrimStart('+').Length > 0;
}
