namespace EliteSIP.SipCore;

/// <summary>
/// Следит за тем, доходит ли до нас опрос сервера.
///
/// <b>Зачем.</b> Регистрация и достижимость — разные вещи, и расходятся они
/// молча. Клиент показывает «На линии», срок регистрации свежий, а INVITE из
/// очереди раздачи до рабочего места не доходит: обратной дороги через NAT уже
/// нет. Asterisk это видит — его qualify не получает ответа, и пир уходит в
/// UNREACHABLE, — а клиент не видит ничего.
///
/// Случай не выдуманный. Архив 18 августа 2026: OPTIONS приходили ровно раз в
/// 60 секунд, потом пропадали на 150, 90, 210 и 270 секунд, и каждый провал
/// кончался в ту же миллисекунду, когда уходил очередной REGISTER. То есть
/// дорога закрывалась и открывалась обратно любым нашим исходящим пакетом, а
/// оператор всё это время считался доступным и лидов не получал.
///
/// <b>Почему именно опрос.</b> Это единственный признак обратной дороги, который
/// у клиента есть. Свои пакеты доходят всегда — они открывают дорогу сами;
/// ответы на них приходят по горячей привязке. Чужой запрос, пришедший по своей
/// воле, — первое, что пропадает, и последнее, что возвращается.
///
/// Тип синхронный и без часов внутри: момент приходит аргументом, поэтому
/// проверяется тестом целиком.
/// </summary>
public sealed class QualifyWatch
{
    /// <summary>
    /// Во сколько раз молчание должно превысить привычный интервал опроса.
    ///
    /// Три: один потерянный OPTIONS — это потерянный пакет, а не потерянная
    /// дорога, и дёргать регистрацию из-за него значит менять редкую беду на
    /// частую. Три подряд на UDP в локальной сети случайностью уже не бывают.
    /// </summary>
    public const int SilenceFactor = 3;

    /// <summary>
    /// Ниже этого выученный интервал не опускается.
    ///
    /// Сразу после REGISTER Asterisk опрашивает пир внеочередно, и такая пара
    /// даёт промежуток в секунды. Без нижней границы он стал бы «привычным
    /// интервалом», а сторож — источником ложных перерегистраций.
    /// </summary>
    public static readonly TimeSpan MinimumInterval = TimeSpan.FromSeconds(30);

    /// <summary>Когда до нас последний раз дошло хоть что-то со стороны сервера.</summary>
    private TimeSpan? _lastHeard;

    /// <summary>Выученный интервал опроса. Наружу — только ради журнала.</summary>
    public TimeSpan? LearnedInterval { get; private set; }

    /// <summary>
    /// Пришёл опрос сервера.
    ///
    /// Интервал берётся минимальный из виденных, а не последний: потери делают
    /// промежутки длиннее, и «последний» после первого же провала задрал бы порог
    /// до бесконечности — сторож ослеп бы ровно тогда, когда нужен.
    /// </summary>
    public void NoteQualify(TimeSpan now)
    {
        TimeSpan? previous = _lastHeard;
        _lastHeard = now;

        if (previous is not TimeSpan last)
        {
            return;
        }

        TimeSpan gap = now - last;
        if (gap <= TimeSpan.Zero)
        {
            return;
        }

        TimeSpan candidate = gap > MinimumInterval ? gap : MinimumInterval;
        LearnedInterval = LearnedInterval is TimeSpan known && known < candidate ? known : candidate;
    }

    /// <summary>
    /// Дорога заведомо открыта — прошёл наш запрос и вернулся ответ.
    ///
    /// Не учит интервал: промежуток от чужого опроса до нашей регистрации к
    /// частоте опроса отношения не имеет.
    /// </summary>
    public void NoteReachable(TimeSpan now) => _lastHeard = now;

    /// <summary>
    /// Потеряна ли обратная дорога.
    ///
    /// Возвращает срок молчания, если пора действовать, и <see langword="null"/>,
    /// если ещё рано или судить не по чему. Сам факт срабатывания сдвигает
    /// отсчёт: следующий раз наступит не раньше, чем через столько же, — иначе на
    /// сервере, до которого не достучаться вовсе, мы бы перерегистрировались в
    /// цикле.
    /// </summary>
    public TimeSpan? SilenceIfLost(TimeSpan now)
    {
        if (LearnedInterval is not TimeSpan interval || _lastHeard is not TimeSpan lastHeard)
        {
            return null;
        }

        TimeSpan silence = now - lastHeard;
        if (silence < interval * SilenceFactor)
        {
            return null;
        }

        _lastHeard = now;
        return silence;
    }
}

/// <summary>Зачем открываем дорогу. Решает, можно ли пропустить.</summary>
public enum SipPathOpenReason
{
    /// <summary>Перед плановой регистрацией.</summary>
    Registration,

    /// <summary>
    /// Перед повтором после отказа. Именно здесь пропускать нельзя: самая
    /// вероятная причина отказа — что дорогу как раз закрыли.
    /// </summary>
    Retry,

    /// <summary>Тик по времени, пока всё хорошо.</summary>
    Periodic,
}

/// <summary>
/// Открывает дорогу до сервера перед тем, как по ней пойдёт SIP.
///
/// Отдельным интерфейсом, а не вызовом стука напрямую: <see cref="SipUserAgent"/>
/// не должен знать ни про ICMP, ни про то, что на другом конце MikroTik. Ему
/// нужно ровно одно — возможность сказать «сейчас будет регистрация» и
/// дождаться. Реализация (стук по портам) приезжает на этапе W11; в тестах на
/// это место встаёт заглушка, которая считает вызовы.
/// </summary>
public interface ISipPathOpener
{
    public Task OpenPathAsync(SipPathOpenReason reason);
}
