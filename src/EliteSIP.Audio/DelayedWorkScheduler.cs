namespace EliteSIP.Audio;

/// <summary>
/// Ставит работу на срок и отдаёт то, чем её можно отменить.
///
/// <b>Отдельным делегатом ради проверяемости.</b> В тракте два решения
/// держатся на отсрочке, и оба — из тех, что ломаются тихо: отложенное
/// освобождение устройства в <see cref="VoiceAudioBus"/> и склейка пачки
/// уведомлений о смене устройств в <see cref="RestartSupervisor"/>. Проверять
/// их настоящим ожиданием секунды значило бы либо стоять секунду на каждом
/// случае, либо получить мигающие тесты. Своя реализация по умолчанию сидит на
/// таймере; тест подставляет ручную.
///
/// <b>Отмена не останавливает то, что уже началось</b> — ни у таймера, ни у
/// очереди, которая была на её месте в оригинале. Оба, кто этим пользуется,
/// обязаны проверять условие ещё раз внутри самой работы, и оба проверяют.
/// </summary>
/// <param name="delay">Через сколько выполнить.</param>
/// <param name="work">Что выполнить.</param>
/// <returns>Освобождение отменяет работу, если она ещё не началась.</returns>
public delegate IDisposable DelayedWorkScheduler(TimeSpan delay, Action work);
