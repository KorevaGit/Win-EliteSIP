namespace EliteSIP.Audio;

/// <summary>
/// Куда сейчас идёт звук разговора и в каком режиме.
///
/// Существует ради одной вещи, которую пользователь замечает сразу, а объяснить
/// её нечем: при звонке через Bluetooth-гарнитуру музыка и системные звуки
/// становятся заметно глуше. Это не наш дефект и не дефект Windows — это
/// Bluetooth: пока микрофон гарнитуры открыт, канал работает в двустороннем
/// режиме, и на воспроизведение остаётся вдвое меньше полосы. Показать это
/// словами дешевле, чем отвечать на вопрос «почему испортился звук».
///
/// <b>Признак режима гарнитуры перенесён не буквально, и это упрощение.</b> На
/// macOS его пришлось нащупывать замерами: у Bluetooth-устройства вывода
/// появлялись входные каналы, а частота падала. Признак был неочевиден,
/// держался на наблюдении и мог сломаться на другой модели наушников. На
/// Windows режим связи — <b>отдельная конечная точка с перечислителем
/// <c>BTHHFENUM</c></b>, и спрашивать не о чем.
///
/// <b>На Windows у этого есть вторая, худшая сторона.</b> Замер W0: Windows
/// поднимает HFP в узкой полосе 8 кГц (CVSD, не mSBC), тогда как на macOS те же
/// AirPods работали в широкой. Поэтому здесь маршрут сообщает не только про
/// глухой звук системы, но и про то, что разговор будет узкополосным — и
/// что <c>G.722</c> на таком устройстве бессмыслен.
/// </summary>
/// <param name="Input">Устройство захвата. <c>null</c> — микрофона нет.</param>
/// <param name="Output">Устройство воспроизведения. <c>null</c> — выхода нет.</param>
public sealed record AudioRoute(AudioDevice? Input, AudioDevice? Output)
{
    /// <summary>Снимок маршрута по системным устройствам для связи.</summary>
    public static AudioRoute Current() => new(
        AudioDeviceCatalog.Default(AudioDeviceDirection.Capture),
        AudioDeviceCatalog.Default(AudioDeviceDirection.Render));

    /// <summary>
    /// Гарнитура работает в режиме двусторонней связи.
    ///
    /// Достаточно одной стороны: пока микрофон гарнитуры открыт, в режим связи
    /// уходит весь канал, а значит и воспроизведение.
    /// </summary>
    public bool IsHeadsetMode =>
        Input?.SwitchesToHeadsetMode == true || Output?.SwitchesToHeadsetMode == true;

    /// <summary>
    /// Разговор пойдёт в узкой полосе, сколько бы ни обещал сервер.
    ///
    /// Смотрит на вход и на выход по отдельности: у гарнитуры в режиме связи
    /// узкополосны обе стороны, но связка «микрофон ноутбука плюс наушники»
    /// вполне может резать полосу только в одну.
    /// </summary>
    public bool IsNarrowband => Input?.IsNarrowband == true || Output?.IsNarrowband == true;

    /// <summary>Строка для журнала и для панели.</summary>
    public string Summary
    {
        get
        {
            string text = $"вход {Input?.Name ?? "нет"} → выход {Output?.Name ?? "нет"}";

            if (IsHeadsetMode)
            {
                text += " (режим гарнитуры: звук системы стал глуше — это Bluetooth, не мы)";
            }

            if (IsNarrowband)
            {
                text += " (узкая полоса: широкополосный кодек не поможет — режет гарнитура)";
            }

            return text;
        }
    }
}
