using EliteSIP.MediaCore;

namespace EliteSIP.Audio;

/// <summary>
/// Настройки разговора, под которые собирается тракт.
///
/// Изменяемых полей нет: настройки переезжают с линии на линию на живом
/// объекте, и запись в них с чужого потока была бы гонкой на ровном месте.
/// Смена настроек — это новая запись и пересборка тракта, а не правка на
/// месте.
///
/// <b>Идентификаторы устройств, а не «uid».</b> В оригинале поле называлось
/// <c>inputDeviceUID</c>, потому что на macOS у устройства было два
/// идентификатора и в настройки клали постоянный. Здесь он один — см.
/// <see cref="AudioDevice"/>.
/// </summary>
public sealed record VoiceAudioConfiguration
{
    /// <summary>
    /// Потолок усиления микрофона — вдвое, то есть +6 дБ.
    ///
    /// Выше нельзя: усиление стоит ПОСЛЕ обработки голоса и после пересчёта в
    /// кодек, то есть умножает уже готовые отсчёты вместе со всем, что в них
    /// попало. Вдвое тихая гарнитура вытягивается, вчетверо — вытягивается
    /// вместе с шумом комнаты и упирается в ограничение.
    /// </summary>
    public const float MicrophoneGainLimit = 2;

    /// <summary>Кодек разговора.</summary>
    public AudioCodec Codec { get; init; } = AudioCodec.Pcmu;

    /// <summary>Длительность пакета.</summary>
    public int PacketTimeMilliseconds { get; init; } = AudioCodecInfo.DefaultPacketTimeMilliseconds;

    /// <summary>
    /// Глубина кольца воспроизведения в кадрах. Защита от роста задержки, если
    /// сеть отдаёт быстрее, чем звуковая карта успевает играть.
    /// </summary>
    public int MaximumPlaybackFrames { get; init; } = 25;

    /// <summary>
    /// Сколько кадров держать наготове перед потоком вывода. Два — это 40 мс:
    /// хватает пережить неровный вызов и не добавляет заметной задержки поверх
    /// джиттер-буфера.
    /// </summary>
    public int TargetPlaybackFrames { get; init; } = 2;

    /// <summary>
    /// На сколько кадров вперёд тракт просит звук.
    ///
    /// Кольцо наполняется с запасом на кадр сверх целевого: устройство будит
    /// поток нерегулярно, и наполнять ровно до цели значит отдавать пустоту при
    /// каждом опоздании на такт.
    ///
    /// <b>Три кадра, а не четыре (с 2 октября 2026).</b> Запас вдвое против
    /// целевого был нужен, пока подача просыпалась по системному таймеру —
    /// раз в 15,6 мс. Теперь её будит сам вывод на каждом такте устройства,
    /// и модель всей цепочки (<c>PlaybackModelTests</c>) при трёх кадрах даёт
    /// ноль сокрытий и ни одного пустого такта вывода, включая зависание
    /// подачи на 45 мс. При двух кадрах такие зависания уже опустошают кольцо —
    /// это щелчок, поэтому меньше трёх не ставить. Выигрыш — 20 мс задержки
    /// приёма: запас всей цепочки с 105 до 90 мс.
    ///
    /// <b>Число живёт здесь, а не в цикле подачи, потому что на нём сходятся
    /// две половины разговора.</b> Тот, кто отдаёт кадры (на живом звонке это
    /// джиттер-буфер <c>MediaSession</c>), обязан быть готов отдать их
    /// столько же вперёд. Иначе спрос постоянно опережает приход из сети:
    /// буфер отдаёт сокрытие, сдвигает ожидаемый номер, и пришедший следом
    /// настоящий пакет объявляется опоздавшим и выбрасывается. Разговор при
    /// этом слышен, но половина его — повторы; поймано на живом звонке
    /// (см. <c>docs/W5-CALL.md</c>).
    /// </summary>
    public int PlaybackLeadFrames => TargetPlaybackFrames + 1;

    /// <summary>Микрофон. <c>null</c> — системный для связи.</summary>
    public string? InputDeviceId { get; init; }

    /// <summary>
    /// Наушники. <c>null</c> — системные для связи.
    ///
    /// <b>Агрегатного устройства здесь не будет.</b> На macOS разные устройства
    /// на вход и выход приходилось сводить приватным агрегатом: там один общий
    /// узел ввода-вывода на оба направления, и развести их иначе нельзя. В
    /// WASAPI это два независимых потока изначально, и агрегат не нужен — но
    /// вместе с ним пропала и бесплатная синхронизация часов, которую он давал.
    /// Отсюда компенсация расхождения часов в этом же этапе: её в оригинале нет
    /// и не могло быть.
    /// </summary>
    public string? OutputDeviceId { get; init; }

    /// <summary>
    /// Отпускать звуковое устройство, когда тракт не нужен.
    ///
    /// Ради Bluetooth-гарнитур: иначе они висят в режиме связи между звонками,
    /// и у всей системы приглушён звук. На Windows это заметнее, чем на macOS —
    /// открытый поток захвата держит гарнитуру в HFP, то есть в моно 8 кГц.
    /// </summary>
    public bool ReleasesDeviceWhenIdle { get; init; } = true;

    /// <summary>
    /// Автоматическая регулировка усиления в обработке голоса.
    ///
    /// По умолчанию выключена — продуктовое решение оригинала, и замеры W0 его
    /// не меняют. На встроенном микрофоне АРУ полезна, на хорошей гарнитуре
    /// «дышит»: подтягивает шум в паузах и приседает на громком слоге.
    /// Эхоподавление и шумодав от неё не зависят.
    /// </summary>
    public bool AutomaticGainControl { get; init; }

    /// <summary>
    /// Шумодав в обработке голоса. По умолчанию включён.
    ///
    /// Он не только убирает фон комнаты, но и добирает то, что оставил
    /// эхоподавитель, — см. замеры в <see cref="VoiceProcessor"/>. Поэтому
    /// выключать его стоит только на гарнитуре.
    /// </summary>
    public bool NoiseSuppression { get; init; } = true;

    /// <summary>
    /// Приглушать голоса вокруг: всё, что заметно тише голоса оператора. По
    /// умолчанию включено.
    ///
    /// Шумодав этого не делает и не умеет — чужую речь он пропускает, как и
    /// свою. См. <see cref="BackgroundVoiceGate"/>.
    /// </summary>
    public bool BackgroundVoiceSuppression { get; init; } = true;

    /// <summary>
    /// Открывать захват в сыром режиме, без обработки системы.
    ///
    /// По умолчанию выключено, и это решение по замеру W0, а не по умолчанию
    /// «как проще». С сырым режимом уровень микрофона перестал гулять — от
    /// −41,5 до −43,1 дБ на девяти прогонах вместо разброса в 26 дБ, — то есть
    /// системная обработка действительно была источником нестабильности,
    /// на которой не сходился эхоподавитель. Но подавления это не прибавило, а
    /// выключает сырой режим и то полезное, что система делает сама.
    ///
    /// Рабочее место оператора — гарнитура, где эха нет по построению, поэтому
    /// по умолчанию системная обработка остаётся. Переключатель нужен для
    /// случая «динамики ноутбука», который проверяется отдельно.
    /// </summary>
    public bool UseRawCapture { get; init; }

    /// <summary>
    /// Усиление микрофона, множителем. Ограничивается
    /// <see cref="MicrophoneGainLimit"/>.
    ///
    /// Настройка рабочего места, а не линии: у оператора одна пара ушей и один
    /// микрофон на все три линии. Поэтому здесь, а не у сессии, и переживает
    /// смену владельца тракта.
    /// </summary>
    public float MicrophoneGain
    {
        get;
        init => field = Clamp(value, MicrophoneGainLimit);
    } = 1;

    /// <summary>
    /// Громкость воспроизведения, множителем, до <see cref="PlaybackVolumeLimit"/>.
    ///
    /// До 2 октября 2026 выше единицы не пускалась: «микшер выше не умеет».
    /// Умножение идёт в тракте, а не в микшере, и после него стоит мягкий
    /// ограничитель (<see cref="SpeechGainControl.Limit"/>) — поэтому вдвое
    /// громче можно без жёсткого среза. Уровень городских линий гуляет на
    /// 10–15 дБ, и тихую линию оператор вытягивает этим ползунком.
    /// </summary>
    public float PlaybackVolume
    {
        get;
        init => field = Clamp(value, PlaybackVolumeLimit);
    } = 1;

    /// <summary>
    /// Предел громкости собеседника: вдвое, +6 дБ. Больше — и на громкой линии
    /// ограничитель работает постоянно, то есть звук сплющивается.
    /// </summary>
    public const float PlaybackVolumeLimit = 2;

    /// <summary>
    /// Выравнивать громкость собеседника: тихую линию поднимать до +10 дБ,
    /// громкую убавлять до −6 дБ. По умолчанию выключено — включает оператор,
    /// если линии у него разные по громкости.
    ///
    /// Работает на речи и замирает в паузах (тот же <see cref="SpeechGainControl"/>,
    /// что у микрофона), поэтому шум линии в паузах не «дышит», а стоит на
    /// прибавке последней фразы.
    /// </summary>
    public bool ReceiveGainControl { get; init; }

    /// <summary>
    /// Сколько терпеть, если тракт не пересобирается. См.
    /// <see cref="AudioRestartSettings"/>: числа, а не готовый счётчик.
    /// </summary>
    public AudioRestartSettings RestartSettings { get; init; } = AudioRestartSettings.Default;

    /// <summary>Сколько отсчётов в кадре при этом кодеке и этой длительности пакета.</summary>
    public int SamplesPerFrame => Codec.SampleCount(PacketTimeMilliseconds);

    /// <summary>
    /// Ограничение множителя.
    ///
    /// Отрицательное усиление — это переворот фазы, а не тишина, и приходит оно
    /// только из испорченных настроек. Ноль оставлен: это законное «выключить».
    /// </summary>
    private static float Clamp(float value, float limit) =>
        float.IsNaN(value) ? 1 : Math.Clamp(value, 0, limit);
}
