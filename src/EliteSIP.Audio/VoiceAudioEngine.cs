namespace EliteSIP.Audio;

/// <summary>
/// Что случилось с трактом.
///
/// Отдельно от диагностики: диагностика — текст для журнала, а на это
/// приложению надо реагировать.
/// </summary>
public abstract record VoiceAudioEvent
{
    // Закрытый конструктор запирает список наследников этим файлом: в C# нет
    // размеченного объединения, и без этого «событие тракта» мог бы объявить
    // кто угодно, а разбор по случаям молча перестал бы быть полным.
    private VoiceAudioEvent()
    {
    }

    /// <summary>Тракт пересобран после смены конфигурации звука.</summary>
    public sealed record Restarted(string Reason) : VoiceAudioEvent;

    /// <summary>
    /// Пересобрать не вышло, но попытки продолжаются: звука сейчас нет, а
    /// разговор ещё жив.
    ///
    /// Отдельно от <see cref="Broken"/> потому, что реакция обязана быть
    /// разной. Временная пропажа устройства снимает его на несколько секунд, и
    /// вешать из-за этого трубку — то же самое, что бросать разговор из-за
    /// одного потерянного пакета. Оператору надо сказать, что звук
    /// восстанавливается, и дать ему восстановиться.
    /// </summary>
    public sealed record Restarting(string Reason, int Attempt) : VoiceAudioEvent;

    /// <summary>Пересобрать не удалось и попытки исчерпаны — звука больше не будет.</summary>
    public sealed record Broken(string Reason) : VoiceAudioEvent;

    /// <summary>Маршрут изменился: другое устройство или другой режим.</summary>
    public sealed record RouteChanged(AudioRoute Route) : VoiceAudioEvent;
}

/// <summary>Кадр для воспроизведения вместе с признаком, настоящий он или спрятанный.</summary>
/// <param name="Payload">Кодированный кадр.</param>
/// <param name="IsConcealment">
/// Кадр не пришёл и подставлен взамен. Воспроизведение накладывает на такой
/// затухание, чтобы повтор не звучал заевшей пластинкой.
/// </param>
public readonly record struct PlaybackFrame(ReadOnlyMemory<byte> Payload, bool IsConcealment);

/// <summary>
/// Обработчики разговора. Переезжают вместе с владением трактом.
///
/// <b>Одной записью, а не пятью свойствами.</b> В оригинале они лежали под
/// общим замком, и по той же причине: пока движок создавался на каждый звонок,
/// обработчики ставились один раз до запуска и больше не менялись; с общим
/// трактом они переезжают с линии на линию на живом объекте, а читают их потоки
/// захвата и подачи. Пять отдельных свойств означали бы, что смена владельца
/// видна потоку звука наполовину: новый обработчик кадров и старый обработчик
/// событий. Здесь набор подменяется одной ссылкой, то есть целиком или никак.
/// </summary>
public sealed record VoiceAudioHandlers
{
    /// <summary>
    /// Куда писать подробности о форматах. Без них разбирать отказы звуковой
    /// подсистемы невозможно: она сообщает номер ошибки, но не то, что именно
    /// не сошлось.
    /// </summary>
    public Action<string>? Diagnostic { get; init; }

    /// <summary>События тракта. Вызывается на служебном потоке, не на потоке звука.</summary>
    public Action<VoiceAudioEvent>? Event { get; init; }

    /// <summary>
    /// Кодированный кадр с микрофона, готовый к отправке в RTP. Вызывается на
    /// потоке захвата — не блокировать.
    /// </summary>
    public Action<ReadOnlyMemory<byte>>? EncodedFrame { get; init; }

    /// <summary>
    /// Распакованные отсчёты того, что мы услышали.
    ///
    /// Диагностический: нужен, чтобы можно было ответить на вопрос «а что
    /// именно приехало», не полагаясь на уши. Без него проверить чужой кодер
    /// нечем — совпадения счётчиков пакетов для этого мало.
    /// </summary>
    public Action<short[]>? DecodedSamples { get; init; }

    /// <summary>
    /// Запрос очередного кадра для воспроизведения.
    ///
    /// Пул, а не толчок: спрашивает подающий поток ровно в том темпе, в каком
    /// звуковая карта забирает отсчёты. Возврат <c>null</c> означает «нечего
    /// играть».
    /// </summary>
    public Func<PlaybackFrame?>? NeedsFrame { get; init; }

    /// <summary>Пустой набор. Ставится тракту, когда его отпустили.</summary>
    public static VoiceAudioHandlers None { get; } = new();
}

/// <summary>
/// Тракт разговора: микрофон, обработка голоса, кодек, воспроизведение.
///
/// <b>Интерфейс, которого в оригинале нет, и это не архитектурное украшение.</b>
/// В оригинале <c>VoiceAudioBus</c> зависел от конкретного
/// <c>VoiceAudioEngine</c>, а тот без звуковой карты не заводится — поэтому
/// шину нельзя было проверить тестом вовсе, и проверялось только владение
/// ключами отдельным типом. Собственный комментарий шины называет ошибку, ради
/// которой она написана, «первой же, которую сделает любой новый путь», — и при
/// этом её было нечем поймать. Здесь шина работает с этим интерфейсом, и
/// порядок операций при захвате, отмена отложенного освобождения и отказ в
/// остановке чужого разговора закрыты тестами без единого устройства.
///
/// <b>Остановка и освобождение — разные вещи, и это существенно.</b>
/// <see cref="Stop"/> прекращает разговор, но оставляет устройство за нами:
/// звонок сразу после отбоя должен подниматься без паузы на открытие.
/// <see cref="IDisposable.Dispose"/> отдаёт устройство системе — и только это
/// возвращает Bluetooth-гарнитуру из режима связи. Кто и когда зовёт второе,
/// решает <see cref="VoiceAudioBus"/>.
/// </summary>
/// <summary>
/// Сколько звук ждёт в тракте, по обе стороны от сети.
///
/// Разложено на две половины, а не сведено в одно число, потому что лечатся они
/// разным: захват — настройками устройства и обработки, воспроизведение — тем,
/// сколько кольцо держит впереди. Одно общее число говорит «много», но не
/// говорит, где именно.
/// </summary>
/// <param name="CaptureMilliseconds">
/// От микрофона до готового кадра: то, что накопилось в буфере устройства, плюс
/// задержка фильтров пересчёта частоты.
/// </param>
/// <param name="PlaybackMilliseconds">
/// От запрошенного кадра до динамика: кольцо плюс то, что устройство ещё не
/// проиграло.
/// </param>
public readonly record struct AudioLatencySnapshot(
    double CaptureMilliseconds,
    double PlaybackMilliseconds)
{
    public double TotalMilliseconds => CaptureMilliseconds + PlaybackMilliseconds;
}

// CA1716 просит переименовать Stop: это ключевое слово Visual Basic. Не
// переименовываем. Продукт на C# и на нём же останется, а «остановить тракт»
// на другом слове читаться перестанет — цена правила здесь испорченное имя
// ради потребителя, которого не будет.
[System.Diagnostics.CodeAnalysis.SuppressMessage(
    "Naming",
    "CA1716:Identifiers should not match keywords",
    Justification = "продукт на C#; остановка тракта — доменное слово, замена ухудшит чтение")]
public interface IVoiceAudioEngine : IDisposable
{
    /// <summary>
    /// Сколько звук ждёт внутри тракта прямо сейчас.
    ///
    /// Числа те же, которые тракт и так считает каждый кадр для эхоподавителя, —
    /// ему нужна задержка между тем, что играет, и тем, что слышит микрофон.
    /// Наружу они отдаются потому, что вторая половина ответа на вопрос «почему
    /// мы перебиваем друг друга» лежит в джиттер-буфере и в сети, а сложить их
    /// может только тот, кто видит и то и другое.
    /// </summary>
    public AudioLatencySnapshot Latency { get; }

    /// <summary>
    /// Обработчики разговора. Подменяются целиком.
    ///
    /// Свойство, а не пять: см. <see cref="VoiceAudioHandlers"/>.
    /// </summary>
    public VoiceAudioHandlers Handlers { get; set; }

    /// <summary>Перестраивает тракт под новые настройки. Тракт должен быть остановлен.</summary>
    public void Reconfigure(VoiceAudioConfiguration configuration);

    /// <summary>
    /// Применяет настройки к тракту, не останавливая разговор.
    ///
    /// Громкость и усиление меняются сразу, обработка голоса — подменой на
    /// ходу, другое устройство — пересборкой, как при его смене в системе.
    /// На остановленном тракте просто запоминает настройки.
    /// </summary>
    public void Apply(VoiceAudioConfiguration configuration);

    /// <summary>Запускает тракт. Бросает, если поднять его не удалось.</summary>
    public void Start();

    /// <summary>
    /// Останавливает тракт, оставляя устройство за собой. Повторный вызов —
    /// вхолостую: сюда приходят и по отбою, и запоздавшим путём.
    /// </summary>
    public void Stop();

    /// <summary>Пересобирает тракт по требованию владельца — смена устройства, ручная пересборка.</summary>
    public void Restart(string reason);
}
