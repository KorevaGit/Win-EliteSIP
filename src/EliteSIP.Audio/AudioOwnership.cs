namespace EliteSIP.Audio;

/// <summary>
/// Ключ владельца тракта.
///
/// В оригинале ту же роль играл <c>ObjectIdentifier</c> — адрес объекта,
/// державшего линию. На Windows от него пришлось отказаться, и не из-за
/// различий языков: адрес умершего объекта переиспользуется, а весь смысл
/// этого типа — узнавать запоздавший путь от живого. Совпадение адресов
/// сделало бы чужой ключ своим ровно в том случае, ради которого проверка и
/// написана. Значение выдаётся один раз и больше никогда не повторяется.
/// </summary>
public readonly record struct AudioOwnerToken
{
    private readonly Guid _value;

    private AudioOwnerToken(Guid value) => _value = value;

    /// <summary>Новый ключ. Каждый вызов даёт значение, которого ещё не было.</summary>
    public static AudioOwnerToken New() => new(Guid.NewGuid());

    /// <summary>Ключ, который не принадлежит никому. Значение по умолчанию.</summary>
    public bool IsNone => _value == Guid.Empty;

    public override string ToString() => IsNone ? "нет" : _value.ToString("N")[..8];
}

/// <summary>Чем кончилась попытка забрать тракт.</summary>
public enum AudioOwnershipOutcome
{
    /// <summary>Тракт был свободен.</summary>
    Granted,

    /// <summary>
    /// Тракт отобран у прежнего владельца — он про это не узнает, и узнать ему
    /// неоткуда: сообщать некому, объект мог уже умереть.
    /// </summary>
    Replaced,

    /// <summary>
    /// Тракт и так наш. Повторный захват — не ошибка: линию можно вернуть в
    /// разговор дважды подряд, если оператор быстро щёлкает.
    /// </summary>
    AlreadyOwned,
}

/// <summary>
/// Кто держит общий аудиотракт.
///
/// Вынесено из шины по той же причине, что и <see cref="AudioRestartPolicy"/>:
/// это решение, а не действие, а всё, что живёт внутри работы с WASAPI,
/// проверяется только руками и на живом железе. Здесь нет ни движка, ни
/// устройства — только ключи, поэтому ошибку видно тестом.
///
/// Ошибка, ради которой тип написан, одна и всегда одинаковая: <b>снятая линия
/// останавливает тракт, который уже забрала другая, живая.</b> Пока движок
/// создавался на каждый звонок, такое было невозможно по построению — каждая
/// линия глушила свой собственный. С общим трактом это первое, что сделает
/// любой запоздавший путь: отложенная финализация, повторный отбой, обработчик,
/// доехавший после переключения линий. Поэтому отпускание требует предъявить
/// тот же ключ, с которым тракт брали, а чужой ключ — тихий отказ, а не
/// ошибка: приходить с ним нормально, а вот заглушить чужой разговор нельзя.
///
/// <b>Класс, а не структура.</b> В оригинале это <c>mutating struct</c>, и там
/// это безопасно: Swift запрещает менять копию, не назвав её изменяемой. В C#
/// изменяемая структура молча копируется при передаче в метод, при захвате в
/// лямбду, при чтении из свойства — и захват тракта «происходит» на копии,
/// которую тут же выбрасывают. Владение бы при этом не изменилось, а ошибка
/// была бы невидимой: тесты на самом типе прошли бы все до одного.
/// </summary>
public sealed class AudioOwnership
{
    private AudioOwnerToken _holder;

    /// <summary>Держит ли кто-нибудь тракт.</summary>
    public bool IsBusy => !_holder.IsNone;

    /// <summary>Наш ли звук сейчас.</summary>
    public bool IsOwner(AudioOwnerToken token) => !token.IsNone && _holder == token;

    /// <summary>Забирает тракт.</summary>
    public AudioOwnershipOutcome Take(AudioOwnerToken token)
    {
        if (token.IsNone)
        {
            // Ключ по умолчанию означает «никто». Пустить его во владельцы —
            // значит сделать тракт занятым тем, кого нельзя предъявить при
            // отпускании: тракт остался бы захвачен навсегда.
            throw new ArgumentException("пустой ключ не может владеть трактом", nameof(token));
        }

        var previous = _holder;
        _holder = token;

        if (previous == token)
        {
            return AudioOwnershipOutcome.AlreadyOwned;
        }

        return previous.IsNone ? AudioOwnershipOutcome.Granted : AudioOwnershipOutcome.Replaced;
    }

    /// <summary>
    /// Снимает владение, кто бы им ни владел.
    ///
    /// <b>Это ровно то, что тип запрещает всем остальным</b>, и потому оно
    /// внутреннее. Нужно одному-единственному месту — захвату тракта: прежнего
    /// владельца отпускает тот, кто забирает, а ключа его у него нет и быть не
    /// может. В оригинале то же самое делалось заменой значения целиком
    /// (<c>ownership = AudioOwnership()</c>) — там это выглядело безобидно и
    /// потому нигде не объяснялось.
    ///
    /// Безопасно оно только под тем же замком, под которым тут же ставится
    /// новый владелец: промежуток, в котором тракт ничей, наружу видеть нельзя.
    /// </summary>
    internal void ReleaseAny() => _holder = default;

    /// <summary>
    /// Отпускает тракт, если он за этим владельцем.
    ///
    /// Возврат <c>false</c> означает «не ваш» — и это единственный ответ,
    /// который защищает живой разговор от чужой остановки.
    /// </summary>
    public bool Release(AudioOwnerToken token)
    {
        if (token.IsNone || _holder != token)
        {
            return false;
        }

        _holder = default;
        return true;
    }
}
